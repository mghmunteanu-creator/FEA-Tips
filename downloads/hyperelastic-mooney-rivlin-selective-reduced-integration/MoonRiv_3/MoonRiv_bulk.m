%*** MoonRiv_bulk ***
% plane strain state

I3=- exy^2 + 2*ex + 2*ey + 4*ex*ey + 1;

I3E =[                           4*ey + 2
                                 4*ex + 2
      - 2*exy^2 + 2*(2*ex + 1)*(2*ey + 1)
                                   -2*exy
                                        0
                                        0];
 
I3EE =[[        0,        4, 8*ey + 4,      0,          0,          0]
       [        4,        0, 8*ex + 4,      0,          0,          0]
       [ 8*ey + 4, 8*ex + 4,        0, -4*exy,          0,          0]
       [        0,        0,   -4*exy,     -2,          0,          0]
       [        0,        0,        0,      0, - 4*ex - 2,      2*exy]
       [        0,        0,        0,      0,      2*exy, - 4*ey - 2]];
 

J3  =sqrt(I3);
J3E =1/2*I3^(-1/2)*I3E;
J3EE=1/2*I3^(-1/2)*I3EE-1/4*I3^(-3/2)*I3E*I3E';
%==========================================================================
% 2nd Piola-Kirchhoff stresses
SS=KK*(J3-1)*J3E;
sx =SS(1);
sy =SS(2);
sz =SS(3);
sxy=SS(4);
%==========================================================================
% D matrix
J3EE=1/2*I3^(-1/2)*I3EE-1/4*I3^(-3/2)*I3E*I3E';
D=KK*(J3-1)*J3EE+KK*J3E*J3E';

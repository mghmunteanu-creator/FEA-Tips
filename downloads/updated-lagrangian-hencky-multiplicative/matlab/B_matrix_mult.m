B1=FF'*([b(1,1) b(2,1);0      0     ]*Fp);
B2=FF'*([0      0     ;b(1,1) b(2,1)]*Fp);

B3=FF'*([b(1,2) b(2,2);0      0     ]*Fp);
B4=FF'*([0      0     ;b(1,2) b(2,2)]*Fp);

B5=FF'*([b(1,3) b(2,3);0      0     ]*Fp);
B6=FF'*([0      0     ;b(1,3) b(2,3)]*Fp);

B7=FF'*([b(1,4) b(2,4);0      0     ]*Fp);
B8=FF'*([0      0     ;b(1,4) b(2,4)]*Fp);

Bt=Uic*[B1+B1' B2+B2' B3+B3' B4+B4' ...
    B5+B5' B6+B6' B7+B7' B8+B8']/2;

B=[Bt(1,1) Bt(1,3) Bt(1,5) Bt(1,7) Bt(1,9)  Bt(1,11) Bt(1,13) Bt(1,15)
    Bt(2,2) Bt(2,4) Bt(2,6) Bt(2,8) Bt(2,10) Bt(2,12) Bt(2,14) Bt(2,16)
    Bt(1,2) Bt(1,4) Bt(1,6) Bt(1,8) Bt(1,10) Bt(1,12) Bt(1,14) Bt(1,16)];

B(3,:)=2*B(3,:);
